# --- Release coordinates --------------------------------------------------------
# The pinned ovstage build: major.minor.patch.buildnumber.githash.
OVSTAGE_VERSION = "0.3.0.1791986420.36fe3c44"

# sync_ovstage_version.py switches this URL and the Python indexes together.
# Native archives are downloaded from the public OVStage GitHub release.
OVSTAGE_ZIP_URL = "https://github.com/NVIDIA-Omniverse/ovstage/releases/download/v{semver}/{archive}"

# Per-platform SHA-256, generated by scripts/sync_ovstage_version.py.
OVSTAGE_DIGESTS = {
    "manylinux_2_35_x86_64": "922a64c3583040ea3ab3262c0e95aa4ac642bef8676b43a02fa262ea14adc387",
    "manylinux_2_35_aarch64": "14d8815694779799768480eaded48ae3c401ab128eca7e18ea2c3f30e385a307",
    "windows-x86_64": "007cd7ef776415c95342985fcf60ba89aa4222a07c914fdd314acb860e0b95a5",
}

SUPPORTED_PLATFORMS = ("manylinux_2_35_x86_64", "manylinux_2_35_aarch64", "windows-x86_64")

# Top-level names a previously-extracted ovstage package may have. _extract_zip refuses to
# delete a destination holding anything else, since --dest can be consumer-supplied.
_OVSTAGE_TREE_ENTRIES = {
    "include", "lib", "bin", "python", "LICENSE", "THIRD-PARTY-NOTICES.txt",
    "VERSION.md", "ovstage-build-info.json",
    "ovstage",  # a previous wheel-layout extraction
}

RETRY_DELAY_SECONDS = 60


def _retry_network(operation, description, timeout, retry_timeout=0):
    """Optionally retry a complete network operation for retry_timeout seconds.

    The callback receives a socket timeout capped by the remaining window. An
    active transfer may finish after the window; no new attempt starts after it.
    Authentication, certificate, local file and payload-validation errors fail
    immediately. A temporary repository 404 is retried for the same pinned URL.
    Zero preserves the default single attempt and original socket timeout.
    """
    if not retry_timeout:
        return operation(timeout)
    deadline = time.monotonic() + retry_timeout
    attempt = 0
    while True:
        attempt += 1
        try:
            return operation(min(timeout, max(1, deadline - time.monotonic())))
        except (urllib.error.URLError, TimeoutError, ConnectionError,
                http.client.IncompleteRead, ssl.SSLEOFError) as error:
            if isinstance(error, urllib.error.HTTPError):
                if error.code not in (404, 408, 429) and not 500 <= error.code < 600:
                    raise
                error.close()
            elif isinstance(error, urllib.error.URLError):
                if isinstance(error.reason, (ssl.SSLCertVerificationError,
                                             FileNotFoundError, PermissionError,
                                             IsADirectoryError, NotADirectoryError)):
                    raise
            remaining = deadline - time.monotonic()
            if remaining <= 0:
                raise
            delay = min(RETRY_DELAY_SECONDS, remaining)
            print("  ovstage: %s attempt %d failed (%s); waiting %.0fs "
                  "(%.0fs retry window remaining)"
                  % (description, attempt, error, delay, remaining),
                  file=sys.stderr, flush=True)
            time.sleep(delay)
            if time.monotonic() >= deadline:
                raise


def _numeric_version(version):
    """Drop the optional fifth component by position: a git hash can be all digits."""
    parts = version.split(".")
    if len(parts) >= 5:
        parts = parts[:4]
    elif parts and not parts[-1].isdigit():
        parts = parts[:-1]
    return ".".join(parts)


def _semver(version):
    """Return the semantic version used in public release tags."""
    return ".".join(version.split(".")[:3])


def _githash(version):
    """Return the fifth component, including all-digit git hashes."""
    parts = version.split(".")
    if len(parts) >= 5:
        return parts[4]
    return None


def _zip_name(version, platform):
    """Name the native archive, including its required git hash."""
    githash = _githash(version)
    if not githash:
        sys.exit("fetch_ovstage_release: OVSTAGE_VERSION %r has no githash component; "
                 "the native archive name requires one (major.minor.patch.build.githash)."
                 % version)
    return "ovstage@%s.%s.%s.zip" % (_numeric_version(version), githash, platform)


def _zip_url(version, platform):
    return OVSTAGE_ZIP_URL.format(
        semver=_semver(version),
        numeric=_numeric_version(version),
        archive=_zip_name(version, platform),
    )


def _digest(platform):
    """The committed SHA-256 for the native archive, or exit with an actionable message."""
    digest = OVSTAGE_DIGESTS.get(platform)
    if not digest:
        sys.exit("fetch_ovstage_release: no sha256 pinned for platform %r in "
                 "OVSTAGE_DIGESTS (ovstage %s). Regenerate the pin with:\n"
                 "  python scripts/sync_ovstage_version.py --version %s"
                 % (platform, OVSTAGE_VERSION, OVSTAGE_VERSION))
    return digest


def _unlink(path):
    """Remove a partial download, tolerating its absence."""
    try:
        os.remove(path)
    except OSError:
        pass


def _sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def _download(url, dest_path, expected_sha256, retry_timeout=0):
    """Download the native archive and verify its mandatory pinned digest.

    Opt-in retries cover the complete transfer, so a new attempt replaces a
    partial file. Payload validation happens once, after a successful transfer.
    """
    want = expected_sha256.split(":", 1)[-1].strip().lower()
    print("  ovstage: downloading %s" % os.path.basename(dest_path))

    def transfer(timeout):
        with urllib.request.urlopen(urllib.request.Request(url), timeout=timeout) as resp, \
                open(dest_path, "wb") as out:
            shutil.copyfileobj(resp, out)
            # HTTPResponse.read(size) can silently accept an early EOF. Detect
            # this inside the retry so the next attempt replaces the partial file.
            content_length = resp.headers.get("Content-Length") if retry_timeout else None
            if content_length is not None and out.tell() < int(content_length):
                raise http.client.IncompleteRead(b"", int(content_length) - out.tell())

    try:
        _retry_network(transfer, os.path.basename(dest_path), timeout=600, retry_timeout=retry_timeout)
    except urllib.error.HTTPError as exc:
        _unlink(dest_path)
        if exc.code == 404:
            sys.exit("fetch_ovstage_release: %s is not published at %s (HTTP 404). The "
                     "pin is ovstage %s; check that this build was released for every "
                     "platform." % (os.path.basename(dest_path), url, OVSTAGE_VERSION))
        sys.exit("fetch_ovstage_release: %s failed with HTTP %s" % (url, exc.code))
    except Exception:
        _unlink(dest_path)
        raise

    size = os.path.getsize(dest_path)
    if size < 4096:  # a tiny body is a server error page
        with open(dest_path, "rb") as f:
            body = f.read(512)
        _unlink(dest_path)
        sys.exit("fetch_ovstage_release: %s looks invalid (size=%d): %r"
                 % (os.path.basename(dest_path), size, body))

    actual = _sha256(dest_path)
    if actual != want:
        # Never leave an unverified payload behind under the artifact's real name.
        _unlink(dest_path)
        sys.exit("fetch_ovstage_release: %s sha256 %s does not match pinned %s -- the "
                 "mirror served a different build than OVSTAGE_VERSION names"
                 % (os.path.basename(dest_path), actual, want))


def _extract_symlink(zf, info, out_path, dest_abs):
    """Recreate a symlink entry, whose payload is its target path.

    Falls back to copying the target where symlinks are unavailable (Windows without
    developer mode).
    """
    target = zf.read(info).decode("utf-8", "replace").strip()
    resolved = os.path.abspath(os.path.join(os.path.dirname(out_path), target))
    if not resolved.startswith(dest_abs + os.sep):
        sys.exit("fetch_ovstage_release: symlink %r escapes dest (-> %r)"
                 % (info.filename, target))
    if os.path.lexists(out_path):
        os.remove(out_path)
    try:
        os.symlink(target, out_path)
        return
    except (OSError, NotImplementedError, AttributeError):
        pass
    if os.path.isfile(resolved):
        shutil.copyfile(resolved, out_path)
    else:
        sys.exit("fetch_ovstage_release: cannot create symlink %s -> %s, and the target is "
                 "not extracted yet" % (out_path, target))


def _extract_zip(zip_path, dest):
    """Extract the native archive into OVSTAGE_DIR.

    The archive is already rooted at the package prefix (include/, lib/, bin/, python/), so
    it lands at dest with no prefix rewriting -- this is the 'package' layout
    ovruntime/cmake/OvstageDependency.cmake resolves.
    """
    if os.path.islink(dest) or os.path.isfile(dest):
        os.remove(dest)
    elif os.path.isdir(dest):
        # --dest can be consumer-supplied (OVPHYSX_OVSTAGE_CACHE_DIR): only wipe a directory
        # that is empty or is recognisably a previous extraction of this package.
        entries = set(os.listdir(dest))
        if entries and not entries <= _OVSTAGE_TREE_ENTRIES:
            sys.exit("fetch_ovstage_release: refusing to overwrite %s -- it is not empty and "
                     "does not look like an extracted ovstage package (found: %s). Point "
                     "--dest at a dedicated directory."
                     % (dest, ", ".join(sorted(entries)[:8])))
        shutil.rmtree(dest)
    os.makedirs(dest)

    dest_abs = os.path.abspath(dest)
    with zipfile.ZipFile(zip_path) as zf:
        for info in zf.infolist():
            if info.filename.endswith("/"):
                continue
            out_path = os.path.abspath(os.path.join(dest, info.filename))
            if not out_path.startswith(dest_abs + os.sep):
                sys.exit("fetch_ovstage_release: archive entry escapes dest: %r" % info.filename)
            os.makedirs(os.path.dirname(out_path), exist_ok=True)

            external_mode = (info.external_attr >> 16) & 0xFFFF
            if stat.S_ISLNK(external_mode):
                # .so version chains are symlinks (libtbb.so.12 -> libtbb.so.12.13); written
                # as regular files they become text stubs the loader rejects.
                _extract_symlink(zf, info, out_path, dest_abs)
                continue

            with zf.open(info) as src, open(out_path, "wb") as out:
                shutil.copyfileobj(src, out)
            mode = external_mode & 0o777
            if mode:
                os.chmod(out_path, mode)

    if not os.path.isdir(os.path.join(dest, "include")) or not os.path.isdir(os.path.join(dest, "bin")):
        sys.exit("fetch_ovstage_release: extracted ovstage at %s is missing include/ or bin/ "
                 "(unexpected archive layout)." % dest)

    # scripts/package_deps.py resolves OVStage license provenance from this path and raises
    # if it is absent, which then fails the SDK install's notices check.
    if not os.path.isfile(os.path.join(dest, "THIRD-PARTY-NOTICES.txt")):
        sys.exit("fetch_ovstage_release: %s has no THIRD-PARTY-NOTICES.txt; the SDK notices "
                 "check (scripts/package_deps.py) requires it." % dest)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--platform", required=True, help=" | ".join(SUPPORTED_PLATFORMS))
    ap.add_argument("--dest", required=True, help="extract the ovstage package here (OVSTAGE_DIR)")
    ap.add_argument("--retry-timeout", type=int,
                    default=os.environ.get("OVSTAGE_FETCH_RETRY_TIMEOUT", "0"),
                    help="retry transient failures for this many seconds per native archive fetch "
                         "(default: OVSTAGE_FETCH_RETRY_TIMEOUT, or 0 for no retries)")
    args = ap.parse_args()
    if args.retry_timeout < 0:
        ap.error("--retry-timeout must be nonnegative")

    # Offline / pre-staged escape hatch: when OVSTAGE_SKIP_FETCH is set, trust that
    # --dest already holds a valid ovstage and do not download (e.g. building against
    # a locally-staged ovstage that is not yet published).
    if os.environ.get("OVSTAGE_SKIP_FETCH"):
        dest = os.path.abspath(args.dest)
        has_pkg = (os.path.isdir(os.path.join(dest, "include"))
                   or os.path.isdir(os.path.join(dest, "ovstage")))
        if not has_pkg:
            sys.exit("fetch_ovstage_release: OVSTAGE_SKIP_FETCH set but %s has no "
                     "staged ovstage (expected include/ or ovstage/)." % dest)
        print("  ovstage: OVSTAGE_SKIP_FETCH set -- using pre-staged %s" % dest)
        return

    if args.platform not in SUPPORTED_PLATFORMS:
        sys.exit("fetch_ovstage_release: unsupported platform %r (expected one of %s)"
                 % (args.platform, ", ".join(SUPPORTED_PLATFORMS)))

    # Resolve the digest before downloading anything: an unpinned platform should fail
    # immediately, not after ~60 MB has already come down the wire.
    zip_digest = _digest(args.platform)

    dest = os.path.abspath(args.dest)
    parent = os.path.dirname(dest)
    os.makedirs(parent, exist_ok=True)

    # --- native package (the C/C++ SDK ovphysx builds against) ---
    archive = _zip_name(OVSTAGE_VERSION, args.platform)
    url = _zip_url(OVSTAGE_VERSION, args.platform)
    print("  ovstage: version=%s archive=%s" % (OVSTAGE_VERSION, archive))
    # Concurrent SDK configures may share the parent cache directory.
    with tempfile.TemporaryDirectory(prefix=".ovstage-", dir=parent) as download_dir:
        zip_tmp = os.path.join(download_dir, archive)
        _download(url, zip_tmp, zip_digest, retry_timeout=args.retry_timeout)
        _extract_zip(zip_tmp, dest)
    print("  ovstage: package extracted to %s" % dest)


if __name__ == "__main__":
    main()
