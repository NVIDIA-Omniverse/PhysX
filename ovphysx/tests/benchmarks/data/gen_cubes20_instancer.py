"""Generate authored point-instancer environments for OutputWrite.

The replicator loses instancer identity, so author every environment. Use the
gen_cubes20.py seed/layout with four-meter spacing; GPU files overlay CPU geometry.

Usage:
    python3 tests/benchmarks/data/gen_cubes20_instancer.py --envs 1024 > \
        tests/benchmarks/data/cubes20_instancer_envs_1024.usda
    python3 tests/benchmarks/data/gen_cubes20_instancer.py --envs 8192 --gpu > \
        tests/benchmarks/data/cubes20_instancer_envs_8192_gpu.usda
"""

import argparse
import math
import random

NUM_CUBES = 20             # == gen_cubes20.NUM_CUBES
CUBE_SIZE = 0.3            # == gen_cubes20.CUBE_SIZE
GROUND_HALF = 10.0         # == gen_cubes20.GROUND_HALF
SEED = 20260603            # == gen_cubes20.SEED -- must match, see the module docstring


def quat_from_axis_angle(ax, ay, az, theta):
    n = math.sqrt(ax * ax + ay * ay + az * az) or 1.0
    ax, ay, az = ax / n, ay / n, az / n
    s = math.sin(theta / 2.0)
    return (math.cos(theta / 2.0), ax * s, ay * s, az * s)


CPU_SCENE_SETTINGS = '''        bool physxScene:enableGPUDynamics = false
        token physxScene:broadphaseType = "MBP"
'''


def scene(gpu: bool, env_count: int, proto_indices: str, positions: str,
          orientations: str, angular_velocities: str) -> str:
    if gpu:
        return f'''#usda 1.0
(
    subLayers = [@cubes20_instancer_envs_{env_count}.usda@]
)
over "World"
{{
    over "physicsScene"
    {{
        bool physxScene:enableGPUDynamics = true
        token physxScene:broadphaseType = "GPU"
    }}
}}
'''
    side = math.ceil(math.sqrt(env_count))
    envs = []
    for i in range(env_count):
        row, col = divmod(i, side)
        envs.append(
            f'        def Xform "env_{i}" (prepend references = </_instancerEnv>)\n'
            '        {\n'
            f'            double3 xformOp:translate = ({col * 4}, 0, {row * 4})\n'
            '            uniform token[] xformOpOrder = ["xformOp:translate"]\n'
            '        }\n'
        )
    return f"""#usda 1.0
(
    defaultPrim = "World"
    metersPerUnit = 1
    upAxis = "Y"
    doc = "GENERATED by gen_cubes20_instancer.py. {env_count} authored environments with {NUM_CUBES} point instances each."
)

class Xform "_instancerEnv"
{{
    def PointInstancer "instancer"
    {{
        def Cube "proto" (
            prepend apiSchemas = ["PhysicsRigidBodyAPI", "PhysicsCollisionAPI", "PhysicsMassAPI"]
        )
        {{
            double size = {CUBE_SIZE}
            float physics:mass = 1.0
        }}
        prepend rel prototypes = </_instancerEnv/instancer/proto>
        int[] protoIndices = [{proto_indices}]
        point3f[] positions = [{positions}]
        quath[] orientations = [{orientations}]
        vector3f[] angularVelocities = [{angular_velocities}]
    }}
}}

def Xform "World"
{{
    def PhysicsScene "physicsScene" (
        prepend apiSchemas = ["PhysxSceneAPI"]
    )
    {{
        vector3f physics:gravityDirection = (0, -1, 0)
        float physics:gravityMagnitude = 9.81
        uint physxScene:timeStepsPerSecond = 240
{CPU_SCENE_SETTINGS}    }}
    def Cube "GroundPlane" (
        prepend apiSchemas = ["PhysicsCollisionAPI"]
    )
    {{
        double size = 1.0
        double3 xformOp:scale = ({GROUND_HALF * 20}, 0.02, {GROUND_HALF * 20})
        double3 xformOp:translate = (0, -0.01, 0)
        uniform token[] xformOpOrder = ["xformOp:translate", "xformOp:scale"]
    }}
    def Xform "envs"
    {{
{"".join(envs)}    }}
}}
"""


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--gpu", action="store_true", help="emit the GPU-dynamics scene settings")
    ap.add_argument("--envs", type=int, choices=(1024, 8192), required=True)
    args = ap.parse_args()

    rng = random.Random(SEED)
    pos, ori, angvel = [], [], []
    for _ in range(NUM_CUBES):
        # Draw order and ranges are gen_cubes20.py's, exactly: tx, tz, ty, then axis/angle, then the
        # angular velocity. Reordering even two draws off the same seed gives different bodies and
        # silently breaks the control this fixture exists to provide.
        tx = rng.uniform(-1.0, 1.0)
        tz = rng.uniform(-1.0, 1.0)
        ty = rng.uniform(0.5, 5.0)
        ax = rng.uniform(-1.0, 1.0)
        ay = rng.uniform(-1.0, 1.0)
        az = rng.uniform(-1.0, 1.0)
        theta = rng.uniform(0.0, 2.0 * math.pi)
        qw, qx, qy, qz = quat_from_axis_angle(ax, ay, az, theta)
        wx = rng.uniform(-3.0, 3.0)
        wy = rng.uniform(-3.0, 3.0)
        wz = rng.uniform(-3.0, 3.0)
        pos.append(f"({tx}, {ty}, {tz})")
        ori.append(f"({qw}, {qx}, {qy}, {qz})")
        angvel.append(f"({wx}, {wy}, {wz})")

    print(
        scene(
            args.gpu,
            args.envs,
            proto_indices=", ".join("0" for _ in range(NUM_CUBES)),
            positions=", ".join(pos),
            orientations=", ".join(ori),
            angular_velocities=", ".join(angvel),
        ),
        end="",
    )


if __name__ == "__main__":
    main()
