"""Generate the particle OutputRead benchmark assets.

The envs are authored rather than cloned because ``ovphysx_clone`` cannot replicate a
particle set: ``IPhysxReplicator`` handles no ``ePTParticleSet`` / ``ePTParticleSystem``,
so cloning a subtree holding one succeeds and silently produces N envs with no particles.
These lanes therefore reuse the deformable family's ``clonesEnvs() == false`` seam.

Each ``env_<i>`` is an internal reference to a ``class`` template prim, so the file is one
env's worth of point data plus N lines. USD retargets the template's relationship targets
into the referencing subtree, which is what gives every env its own particle SYSTEM as
well as its own set, the shape a cloned RL scene has. The template being a ``class``
keeps it abstract, so it is not parsed and simulated as an N+1th env.

A particle set's row count is exactly the length of the authored ``points`` array (unlike
a deformable, whose simulation mesh comes out of cooking).

GPU-only, by construction: the runtime only registers particles on a GPU-capable scene,
and the ovx read refuses a particle column with no CUDA context (ADR-0008 Decision 9).

Regenerate:

    python gen_particles.py

Requires no USD install to run. Validate the output with one if you have it:

    python -c "from pxr import Usd; Usd.Stage.Open('particles_envs_128.usda')"
"""

import math
import os

# The size registered in OutputRead.cpp, matched to the deformable lane so the two families
# can be read against each other at the same N. 128 and not more: a 512-set scene exhausts a
# 16 GB card.
ENV_COUNTS = (128,)

# Particles per set, as a cube edge: 4^3 = 64. Deliberately small. A large per-set count
# would swamp the per-set costs this measures with copy bandwidth.
PARTICLES_PER_EDGE = 4

# Spacing between particles, and between envs. The env spacing has to exceed the set's
# own extent or neighbouring envs interact, which turns a read benchmark into a solver
# benchmark.
PARTICLE_SPACING = 0.2
ENV_SPACING = 10.0

# Particle radius. particleContactOffset must be >= this or the runtime rejects the
# system. It is kept comfortably above so a jittered start does not trip it.
PARTICLE_WIDTH = 0.1
CONTACT_OFFSET = 0.2


def build_points(edge):
    """A cube of particles, centred on the env origin."""
    half = (edge - 1) * PARTICLE_SPACING * 0.5
    pts = []
    for x in range(edge):
        for y in range(edge):
            for z in range(edge):
                pts.append(
                    (
                        x * PARTICLE_SPACING - half,
                        y * PARTICLE_SPACING - half + 2.0,  # lifted, so the set falls
                        z * PARTICLE_SPACING - half,
                    )
                )
    return pts


def fmt_points(pts):
    return "[" + ", ".join("(%g, %g, %g)" % p for p in pts) + "]"


def fmt_zeros(n):
    return "[" + ", ".join(["(0, 0, 0)"] * n) + "]"


def fmt_widths(n):
    return "[" + ", ".join(["%g" % PARTICLE_WIDTH] * n) + "]"


TEMPLATE = '''#usda 1.0
(
    defaultPrim = "World"
    metersPerUnit = 1
    upAxis = "Y"
    doc = "GENERATED by gen_particles.py -- do not edit by hand. %(env_count)d particle envs, each one PhysxParticleSystem and one particle set of %(particle_count)d particles (%(edge)d^3). Envs are authored rather than cloned because the replicator does not copy particle sets; see the script."
)

# The per-env template. A class, so it composes where it is referenced and the default
# traversal predicate skips it here -- it is not an N+1th env. The particleSystem rel
# points INSIDE the template, so each reference retargets it into its own env.
class Xform "_particleEnv"
{
    def PhysxParticleSystem "particleSystem"
    {
        float particleContactOffset = %(contact_offset)g
        bool particleSystemEnabled = 1
        rel simulationOwner = </World/physicsScene>
    }

    def Points "particles" (
        prepend apiSchemas = ["PhysxParticleSetAPI"]
    )
    {
        point3f[] points = %(points)s
        vector3f[] velocities = %(zeros)s
        float[] widths = %(widths)s
        bool physxParticle:fluid = 0
        bool physxParticle:particleEnabled = 1
        rel physxParticle:particleSystem = </_particleEnv/particleSystem>
    }
}

def Xform "World"
{
    # GPU dynamics and a GPU broadphase are not tuning here: the runtime only registers a
    # particle system on a GPU-capable scene, so without these the asset loads and every
    # lane reads zero groups.
    def PhysicsScene "physicsScene" (
        prepend apiSchemas = ["PhysxSceneAPI"]
    )
    {
        vector3f physics:gravityDirection = (0, -1, 0)
        float physics:gravityMagnitude = 9.81
        bool physxScene:enableGPUDynamics = true
        # NOT `uniform token`, though the schema declares it uniform. The parser does not pick the
        # attribute up with that variability, so the scene comes back with a non-GPU broadphase,
        # PhysXScene::isFullGpuPipelineAvailable() returns false, and every particle system in the
        # asset is rejected at load with "Particles feature is only supported on GPU". The lane then
        # reports Skipped rather than failing, which is how this went unnoticed. Every other asset
        # in this directory declares it plainly for the same reason.
        token physxScene:broadphaseType = "GPU"
    }

    def Xform "envs"
    {
%(envs)s    }
}
'''


def generate(env_count):
    pts = build_points(PARTICLES_PER_EDGE)

    side = int(math.ceil(math.sqrt(env_count)))
    envs = []
    for i in range(env_count):
        row, col = divmod(i, side)
        envs.append(
            '        def Xform "env_%d" (\n'
            "            prepend references = </_particleEnv>\n"
            "        )\n"
            "        {\n"
            "            double3 xformOp:translate = (%g, 0, %g)\n"
            '            uniform token[] xformOpOrder = ["xformOp:translate"]\n'
            "        }\n" % (i, col * ENV_SPACING, row * ENV_SPACING)
        )

    return TEMPLATE % {
        "env_count": env_count,
        "particle_count": len(pts),
        "edge": PARTICLES_PER_EDGE,
        "contact_offset": CONTACT_OFFSET,
        "points": fmt_points(pts),
        "zeros": fmt_zeros(len(pts)),
        "widths": fmt_widths(len(pts)),
        "envs": "".join(envs),
    }


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    for env_count in ENV_COUNTS:
        path = os.path.join(here, "particles_envs_%d.usda" % env_count)
        text = generate(env_count)
        with open(path, "w", newline="\n") as f:
            f.write(text)
        print("wrote %s (%.1f KB)" % (path, len(text) / 1024.0))


if __name__ == "__main__":
    main()
