from pathlib import Path

from . import utils


AUTOGENERATED_MARKER = b"// This code is auto-generated by the PhysX Clang metadata generator."


def _normalized_nonempty_lines(data):
	return tuple(line.rstrip() for line in data.replace(b"\r\n", b"\n").split(b"\n") if line.strip())


def _legacy_generated_lines(canonical_lines):
	spdx_lines = tuple(line for line in canonical_lines if line.startswith(b"// SPDX-"))
	attribution_lines = tuple(line for line in canonical_lines if not line.startswith(b"// SPDX-"))
	if not spdx_lines or not attribution_lines:
		raise RuntimeError("canonical boilerplate must contain SPDX and attribution lines")
	return spdx_lines + tuple(reversed(attribution_lines))


def canonicalize_generated_file(path, canonical_template):
	data = path.read_bytes()
	marker_offset = data.find(AUTOGENERATED_MARKER)
	if marker_offset < 0:
		raise RuntimeError(f"{path}: missing metadata generator marker")

	prefix_lines = _normalized_nonempty_lines(data[:marker_offset])
	canonical_lines = _normalized_nonempty_lines(canonical_template)
	if prefix_lines not in (canonical_lines, _legacy_generated_lines(canonical_lines)):
		raise RuntimeError(f"{path}: unexpected generated copyright preamble")

	newline = b"\r\n" if b"\r\n" in data[:marker_offset] else b"\n"
	canonical = canonical_template.replace(b"\r\n", b"\n").rstrip(b"\n")
	canonical = canonical.replace(b"\n", newline)
	return canonical + newline + newline + data[marker_offset:]


def canonicalize_generated_headers(target_dir, template_path):
	target_dir = Path(target_dir)
	template_path = Path(template_path)
	canonical_template = template_path.read_bytes()

	generated_files = sorted(Path(path) for path in utils.list_autogen_files(str(target_dir)))
	if not generated_files:
		raise RuntimeError(f"{target_dir}: no generated metadata files found")

	updates = []
	for path in generated_files:
		updates.append((path, canonicalize_generated_file(path, canonical_template)))

	for path, updated in updates:
		if updated != path.read_bytes():
			path.write_bytes(updated)
